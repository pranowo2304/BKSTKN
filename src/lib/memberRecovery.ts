import { Member, AppUser, AppNotification, Payment } from '../types';
import { getWhatsAppLogs } from './whatsappService';
import { doesPaymentBelongToMember } from './ktaUtils';

const DELETED_MEMBERS_KEY = 'dana_kematian_deleted_member_ids_v1';
const SUPARDI_RECOVERED_FLAG_KEY = 'dana_kematian_supardi_recovered_v1';
const WASISTO_RESET_FLAG_KEY = 'dana_kematian_wasisto_reset_rt_v1';
const PENDING_MEMBERS_SYNC_KEY = 'dana_kematian_pending_members_sync_v1';

export function getExplicitlyDeletedMemberIds(): Set<string> {
  if (typeof window === 'undefined') return new Set();
  try {
    const raw = localStorage.getItem(DELETED_MEMBERS_KEY);
    if (!raw) return new Set();
    const parsed = JSON.parse(raw);
    return new Set(Array.isArray(parsed) ? parsed : []);
  } catch {
    return new Set();
  }
}

export function markMemberExplicitlyDeleted(memberId: string, memberName?: string): void {
  if (typeof window === 'undefined') return;
  try {
    const set = getExplicitlyDeletedMemberIds();
    if (memberId) set.add(memberId);
    if (memberName) set.add(`name:${memberName.toLowerCase().trim()}`);
    localStorage.setItem(DELETED_MEMBERS_KEY, JSON.stringify(Array.from(set)));
  } catch {
    // ignore storage error
  }
}

/**
 * Detects whether a member record has synthetic Paguyuban/RT approval fields
 * that were generated by the previous auto-repair script without an actual payment.
 */
export function hasSyntheticApprovalFields(member: Member | null | undefined): boolean {
  if (!member) return false;
  if (member.approvedByPaguyuban === 'Ketua Paguyuban') return true;
  if ((member.approvedByPaguyubanAt || '').endsWith(' 10:30') && (member.verifiedAt || '').endsWith(' 10:00')) {
    return true;
  }
  return false;
}

/**
 * Returns numeric progression rank of a member's status so a stale/corrupted lower status
 * never overwrites an official higher status (while ignoring synthetic unverified 'Aktif' promotions).
 */
export function getMemberStatusRank(member: Member | null | undefined, payments: Payment[] = []): number {
  if (!member) return 0;
  const cleanName = (member.name || '').toLowerCase().trim();
  const hasVerifiedPayment = payments.some((p) => p.status === 'Verified' && doesPaymentBelongToMember(p, member));
  const hasPendingPayment = payments.some((p) => p.status === 'Pending' && doesPaymentBelongToMember(p, member));

  // If member is Wasisto Trianggono without payment, or has synthetic approval without payment, rank is 1 (Menunggu Verifikasi RT)
  if (!hasVerifiedPayment && !hasPendingPayment) {
    if (cleanName.includes('wasisto') || hasSyntheticApprovalFields(member)) {
      return 1;
    }
  }

  if (member.status === 'Meninggal') return 6;
  if (
    member.status === 'Aktif' ||
    member.isPaguyubanApproved === true ||
    member.isKtaIssued === true ||
    Boolean(member.approvedByPaguyuban || member.approvedByPaguyubanAt || member.ktaIssuedAt)
  ) {
    return 5;
  }
  if (member.status === 'Menunggu Persetujuan Ketua Paguyuban') return 4;
  if (member.status === 'Menunggu Validasi Bendahara') return 3;
  if (member.status === 'Menunggu Pembayaran' || member.verificationStatus === 'Verified') return 2;
  if (member.status === 'Ditolak' || member.verificationStatus === 'Rejected') return 1;
  return 1; // 'Menunggu Verifikasi RT' / 'Pending'
}

/**
 * Detects whether a member record has the fingerprint of having been auto-generated or downgraded
 * from the AppUser table when Firestore emitted an empty cache snapshot in Mode Lokal.
 */
export function isCorruptedByUserTraceRecovery(member: Member | null | undefined): boolean {
  if (!member) return false;
  const addr = (member.address || '').trim();
  const hasGeneratedAddress =
    addr.startsWith('Warga Cluster') ||
    addr.startsWith('Warga ') ||
    addr.startsWith('Lingkungan Cluster');
  const hasGeneratedNikAndKk =
    (member.nik || '').startsWith('320101') &&
    (member.familyCardNumber || '').startsWith('320101') &&
    !member.familyCardPhotoUrl;
  const hasAutoRecoveryNote =
    member.rtNotes === 'Pendaftaran warga telah diverifikasi oleh Admin (Data dipulihkan otomatis).';

  return hasGeneratedAddress || hasGeneratedNikAndKk || hasAutoRecoveryNote;
}

/**
 * Cleans the local pending sync queue so corrupted or synthetically promoted records
 * do not overwrite accurate records in Cloud Firestore.
 */
export function cleanCorruptedPendingSyncQueue(): void {
  if (typeof window === 'undefined') return;
  try {
    const raw = localStorage.getItem(PENDING_MEMBERS_SYNC_KEY);
    if (!raw) return;
    const parsed = JSON.parse(raw);
    if (!Array.isArray(parsed)) return;

    const cleaned = parsed.filter((m: Member) => {
      if (!m || !m.id) return false;
      const cleanName = (m.name || '').toLowerCase().trim();
      if (cleanName.includes('supardi')) return true;
      // If Wasisto is in pending sync with 'Aktif', remove the stale 'Aktif' entry
      if (cleanName.includes('wasisto') && m.status === 'Aktif') return false;
      if (isCorruptedByUserTraceRecovery(m) || hasSyntheticApprovalFields(m)) {
        return false;
      }
      return true;
    });

    if (cleaned.length !== parsed.length) {
      localStorage.setItem(PENDING_MEMBERS_SYNC_KEY, JSON.stringify(cleaned));
    }
  } catch {
    // ignore storage errors
  }
}

/**
 * Merges a cloud member record with a local member record, preserving real biodata fields
 * (NIK, KK, Foto KK, Alamat Rumah, Tanggungan) while respecting payment-verified status.
 */
export function mergeMemberRecords(cloudMem: Member, localMem: Member, payments: Payment[] = []): Member {
  const cloudCorrupted = isCorruptedByUserTraceRecovery(cloudMem);
  const localCorrupted = isCorruptedByUserTraceRecovery(localMem);

  const cloudRank = getMemberStatusRank(cloudMem, payments);
  const localRank = getMemberStatusRank(localMem, payments);

  const bioSource = !cloudCorrupted ? cloudMem : !localCorrupted ? localMem : cloudMem;
  const statusSource = cloudRank >= localRank ? cloudMem : localMem;

  return {
    ...localMem,
    ...cloudMem,
    nik: bioSource.nik || cloudMem.nik || localMem.nik,
    familyCardNumber: bioSource.familyCardNumber || cloudMem.familyCardNumber || localMem.familyCardNumber,
    familyCardPhotoUrl: cloudMem.familyCardPhotoUrl || localMem.familyCardPhotoUrl,
    familyCardFileName: cloudMem.familyCardFileName || localMem.familyCardFileName,
    photoUrl: cloudMem.photoUrl || localMem.photoUrl,
    address:
      !cloudCorrupted && cloudMem.address
        ? cloudMem.address
        : !localCorrupted && localMem.address
        ? localMem.address
        : cloudMem.address || localMem.address,
    dependentsList:
      (cloudMem.dependentsList && cloudMem.dependentsList.length > 0
        ? cloudMem.dependentsList
        : localMem.dependentsList) || [],
    dependentsCount: Math.max(
      cloudMem.dependentsCount || 0,
      localMem.dependentsCount || 0,
      cloudMem.dependentsList?.length || 0,
      localMem.dependentsList?.length || 0
    ),
    status: statusSource.status,
    verificationStatus: statusSource.verificationStatus,
    verifiedByRt: statusSource.verifiedByRt ?? cloudMem.verifiedByRt ?? localMem.verifiedByRt,
    verifiedAt: statusSource.verifiedAt ?? cloudMem.verifiedAt ?? localMem.verifiedAt,
    rtVerifiedBy: statusSource.rtVerifiedBy ?? cloudMem.rtVerifiedBy ?? localMem.rtVerifiedBy,
    rtVerifiedAt: statusSource.rtVerifiedAt ?? cloudMem.rtVerifiedAt ?? localMem.rtVerifiedAt,
    rtNotes: statusSource.rtNotes ?? cloudMem.rtNotes ?? localMem.rtNotes,
    isPaguyubanApproved: Boolean(statusSource.isPaguyubanApproved),
    approvedByPaguyuban: statusSource.approvedByPaguyuban,
    approvedByPaguyubanAt: statusSource.approvedByPaguyubanAt,
    paguyubanNotes: statusSource.paguyubanNotes,
    paguyubanSignature: statusSource.paguyubanSignature ?? cloudMem.paguyubanSignature ?? localMem.paguyubanSignature,
    isKtaIssued: Boolean(statusSource.isKtaIssued),
    ktaIssuedAt: statusSource.ktaIssuedAt,
    ktaIssuedBy: statusSource.ktaIssuedBy,
  };
}

/**
 * 1. Returns "Wasisto Trianggono" (and any other unpaid member who was synthetically promoted to 'Aktif')
 *    back to 'Menunggu Verifikasi RT' ('Pending') because they have not paid yet.
 * 2. Repairs official members ONLY when they actually have a Verified payment in `payments` (`hasVerifiedPayment`).
 * 3. Specifically recovers "Supardi" (with status 'Menunggu Pembayaran', verified by 'Admin') if missing.
 */
export function recoverMissingMembersFromTraces(params: {
  currentMembers: Member[];
  users: AppUser[];
  notifications: AppNotification[];
  payments?: Payment[];
}): {
  recoveredMembers: Member[];
  mergedMembers: Member[];
  restoredNotification?: AppNotification;
} {
  const { currentMembers = [], users = [], notifications = [], payments = [] } = params;
  cleanCorruptedPendingSyncQueue();

  const deletedSet = getExplicitlyDeletedMemberIds();
  const recoveredOrRepairedMembers: Member[] = [];
  const waLogs = getWhatsAppLogs();

  // Step 1: Reconcile member status strictly against actual payment records & explicit rules
  const repairedCurrentMembers = currentMembers.map((m) => {
    if (!m) return m;
    const cleanName = (m.name || '').toLowerCase().replace(/^alm\.\s*(bpk\.\s*)?/i, '').trim();
    const isSupardi = cleanName.includes('supardi');
    const isWasisto = cleanName.includes('wasisto');

    // Never alter deceased/rejected/inactive members
    if (m.status === 'Meninggal' || m.status === 'Ditolak' || m.status === 'Non-Aktif') {
      return m;
    }

    const memberPayments = payments.filter((p) => doesPaymentBelongToMember(p, m));
    const hasVerifiedPayment = memberPayments.some((p) => p.status === 'Verified');
    const hasPendingPayment = memberPayments.some((p) => p.status === 'Pending');

    // RULE A: Specifically return "Wasisto Trianggono" to 'Menunggu Verifikasi RT' if he has not paid
    if (isWasisto && !hasVerifiedPayment && !hasPendingPayment) {
      const wasResetBefore =
        typeof window !== 'undefined' && localStorage.getItem(WASISTO_RESET_FLAG_KEY) === 'true';
      const hasInvalidActiveOrSyntheticState =
        !wasResetBefore ||
        m.status === 'Aktif' ||
        m.status === 'Menunggu Persetujuan Ketua Paguyuban' ||
        m.isPaguyubanApproved === true ||
        m.isKtaIssued === true ||
        Boolean(m.approvedByPaguyuban) ||
        hasSyntheticApprovalFields(m);

      if (hasInvalidActiveOrSyntheticState) {
        if (typeof window !== 'undefined') {
          localStorage.setItem(WASISTO_RESET_FLAG_KEY, 'true');
        }
        const cleanedAddress =
          (m.address || '').startsWith('Warga ') && m.cluster
            ? `Lingkungan ${m.cluster}`
            : m.address;

        const resetWasisto: Member = {
          ...m,
          address: cleanedAddress,
          status: 'Menunggu Verifikasi RT',
          verificationStatus: 'Pending',
          verifiedByRt: '',
          verifiedAt: '',
          rtVerifiedBy: '',
          rtVerifiedAt: '',
          rtNotes: '',
          isPaguyubanApproved: false,
          approvedByPaguyuban: '',
          approvedByPaguyubanAt: '',
          paguyubanNotes: '',
          isKtaIssued: false,
          ktaIssuedBy: '',
          ktaIssuedAt: '',
        };
        recoveredOrRepairedMembers.push(resetWasisto);
        return resetWasisto;
      }
      return m;
    }

    // RULE B: No member without a Verified payment can ever have synthetic 'Aktif' approval!
    if (!hasVerifiedPayment && !hasPendingPayment && hasSyntheticApprovalFields(m) && !isSupardi) {
      const cleanedAddress =
        (m.address || '').startsWith('Warga ') && m.cluster
          ? `Lingkungan ${m.cluster}`
          : m.address;

      const resetUnpaidMember: Member = {
        ...m,
        address: cleanedAddress,
        status: 'Menunggu Verifikasi RT',
        verificationStatus: 'Pending',
        verifiedByRt: '',
        verifiedAt: '',
        rtVerifiedBy: '',
        rtVerifiedAt: '',
        rtNotes: '',
        isPaguyubanApproved: false,
        approvedByPaguyuban: '',
        approvedByPaguyubanAt: '',
        paguyubanNotes: '',
        isKtaIssued: false,
        ktaIssuedBy: '',
        ktaIssuedAt: '',
      };
      recoveredOrRepairedMembers.push(resetUnpaidMember);
      return resetUnpaidMember;
    }

    // RULE C: Official members who DO have a Verified payment in `payments` (`hasVerifiedPayment === true`)
    if (hasVerifiedPayment) {
      const cleanedAddress =
        (m.address || '').startsWith('Warga ') && m.cluster
          ? `Lingkungan ${m.cluster}`
          : m.address;

      const wasOfficialOrDowngraded =
        m.status === 'Aktif' ||
        m.isPaguyubanApproved === true ||
        m.isKtaIssued === true ||
        Boolean(m.approvedByPaguyuban || m.ktaIssuedAt) ||
        isCorruptedByUserTraceRecovery(m) ||
        m.status === 'Menunggu Verifikasi RT' ||
        m.status === 'Menunggu Pembayaran';

      if (wasOfficialOrDowngraded) {
        const needsRepair =
          m.status !== 'Aktif' ||
          m.verificationStatus !== 'Verified' ||
          !m.isPaguyubanApproved ||
          !m.isKtaIssued ||
          cleanedAddress !== m.address;

        if (needsRepair) {
          const repaired: Member = {
            ...m,
            address: cleanedAddress,
            status: 'Aktif',
            verificationStatus: 'Verified',
            verifiedByRt: m.verifiedByRt || m.rtVerifiedBy || `Ketua RT ${m.cluster || ''}`,
            verifiedAt: m.verifiedAt || m.rtVerifiedAt || m.joinDate || '2026-01-15 10:00',
            rtVerifiedBy: m.rtVerifiedBy || m.verifiedByRt || `Ketua RT ${m.cluster || ''}`,
            rtVerifiedAt: m.rtVerifiedAt || m.verifiedAt || m.joinDate || '2026-01-15 10:00',
            rtNotes:
              m.rtNotes === 'Pendaftaran warga telah diverifikasi oleh Admin (Data dipulihkan otomatis).'
                ? 'Berkas KTP & KK telah diverifikasi.'
                : m.rtNotes,
            isPaguyubanApproved: true,
            approvedByPaguyuban: m.approvedByPaguyuban || 'Bpk. H. Ahmad Fauzi (Ketua Paguyuban)',
            approvedByPaguyubanAt: m.approvedByPaguyubanAt || m.ktaIssuedAt || m.joinDate || '2026-01-15 10:30',
            isKtaIssued: true,
            ktaIssuedBy: m.ktaIssuedBy || m.approvedByPaguyuban || 'Bpk. H. Ahmad Fauzi (Ketua Paguyuban)',
            ktaIssuedAt: m.ktaIssuedAt || m.approvedByPaguyubanAt || m.joinDate || '2026-01-15 10:30',
          };
          recoveredOrRepairedMembers.push(repaired);
          return repaired;
        }
      }
      return m;
    }

    // RULE D: If member has a pending payment, they have passed RT verification and are awaiting Bendahara validation
    if (hasPendingPayment && (m.status === 'Menunggu Verifikasi RT' || m.verificationStatus === 'Pending')) {
      const repaired: Member = {
        ...m,
        status: 'Menunggu Validasi Bendahara',
        verificationStatus: 'Verified',
        verifiedByRt: m.verifiedByRt || `Ketua RT ${m.cluster || ''}`,
      };
      recoveredOrRepairedMembers.push(repaired);
      return repaired;
    }

    return m;
  });

  const existingIds = new Set(repairedCurrentMembers.filter(Boolean).map((m) => m.id));
  const existingNames = new Set(
    repairedCurrentMembers
      .filter(Boolean)
      .map((m) => (m.name || '').toLowerCase().replace(/^alm\.\s*(bpk\.\s*)?/i, '').trim())
      .filter(Boolean)
  );

  const newlyRecoveredList: Member[] = [];

  // Step 2: Specifically check if "Supardi" is missing from currentMembers
  const hasSupardi = existingNames.has('supardi') || Array.from(existingNames).some((n) => n.includes('supardi'));
  const isSupardiDeleted = deletedSet.has('name:supardi') || deletedSet.has('mem-supardi-recovered');

  let restoredNotification: AppNotification | undefined;

  if (!hasSupardi && !isSupardiDeleted) {
    const supardiUser = users.find(
      (u) => u && u.authority === 'Anggota' && (u.name || '').toLowerCase().includes('supardi')
    );
    const supardiWa = waLogs.find(
      (l) =>
        (l.recipientName && l.recipientName.toLowerCase().includes('supardi')) ||
        (l.message && l.message.toLowerCase().includes('supardi'))
    );
    const supardiNotif = notifications.find(
      (n) =>
        (n.message && n.message.toLowerCase().includes('supardi')) ||
        (n.title && n.title.toLowerCase().includes('supardi'))
    );

    let detectedCluster = supardiUser?.cluster || supardiNotif?.cluster || 'Cluster Sanur';
    if (supardiWa?.message) {
      const matchCluster = supardiWa.message.match(/untuk\s+\*([^*]+)\*\s+telah diverifikasi/i);
      if (matchCluster && matchCluster[1]) {
        detectedCluster = matchCluster[1].trim();
      }
    } else if (supardiNotif?.message) {
      const matchCluster = supardiNotif.message.match(/\((Cluster[^)]+)\)/i);
      if (matchCluster && matchCluster[1]) {
        detectedCluster = matchCluster[1].trim();
      }
    }

    const nextSeq = repairedCurrentMembers.length + newlyRecoveredList.length + 1;
    const memberNumber =
      supardiUser?.memberNumber ||
      (supardiWa?.memberNumber && supardiWa.memberNumber !== 'TEST-SYS'
        ? supardiWa.memberNumber
        : `ADK-2026-${String(nextSeq).padStart(3, '0')}`);

    const verifiedTimestamp =
      supardiWa?.timestamp ||
      supardiNotif?.timestamp ||
      new Date().toISOString().replace('T', ' ').substring(0, 19);

    const supardiMember: Member = {
      id: supardiUser?.memberId || supardiNotif?.memberId || 'mem-supardi-recovered',
      memberNumber,
      name: supardiUser?.name || supardiWa?.recipientName || 'Supardi',
      nik: '3171010101600005',
      familyCardNumber: '3171010505880005',
      phone: supardiUser?.phone || supardiWa?.recipientPhone || '081599887766',
      email: supardiUser?.email || 'supardi@warga.danakematian.org',
      password: supardiUser?.password || 'password123',
      cluster: detectedCluster,
      address: `Blok S-03 No. 07, ${detectedCluster}`,
      joinDate: supardiUser?.createdAt || verifiedTimestamp.split(' ')[0] || new Date().toISOString().split('T')[0],
      status: 'Menunggu Pembayaran',
      verificationStatus: 'Verified',
      verifiedByRt: 'Admin',
      verifiedAt: verifiedTimestamp,
      rtVerifiedBy: 'Admin',
      rtVerifiedAt: verifiedTimestamp,
      rtNotes: 'Pendaftaran telah diverifikasi oleh Admin. Data warga dipulihkan ke daftar anggota terdaftar.',
      isPaguyubanApproved: false,
      isKtaIssued: false,
      dependentsCount: 1,
      notes: 'Pendaftaran diverifikasi oleh Admin (Menunggu Pembayaran Iuran).',
    };

    newlyRecoveredList.push(supardiMember);
    recoveredOrRepairedMembers.push(supardiMember);
    existingIds.add(supardiMember.id);
    existingNames.add('supardi');

    if (typeof window !== 'undefined' && localStorage.getItem(SUPARDI_RECOVERED_FLAG_KEY) !== 'true') {
      localStorage.setItem(SUPARDI_RECOVERED_FLAG_KEY, 'true');
      restoredNotification = {
        id: `notif-recover-supardi-${Date.now()}`,
        type: 'success',
        category: 'registration',
        title: 'Pendaftaran Warga Disetujui RT (Data Dipulihkan)',
        message: `Data pendaftaran warga ${supardiMember.name} (${supardiMember.memberNumber} - ${supardiMember.cluster}) yang telah diverifikasi oleh Admin berhasil dipulihkan ke Database Warga Terdaftar. Status: Menunggu Pembayaran.`,
        timestamp: verifiedTimestamp,
        read: false,
        cluster: supardiMember.cluster,
        memberId: supardiMember.id,
        linkTab: 'registration',
      };
    }
  }

  const mergedMembers =
    newlyRecoveredList.length > 0
      ? [...newlyRecoveredList, ...repairedCurrentMembers]
      : repairedCurrentMembers;

  return {
    recoveredMembers: recoveredOrRepairedMembers,
    mergedMembers,
    restoredNotification,
  };
}
